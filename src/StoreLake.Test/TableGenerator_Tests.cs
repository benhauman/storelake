namespace StoreLake.Test
{
    using System.Data;
    using Microsoft.VisualStudio.TestTools.UnitTesting;
    using StoreLake.Sdk.CodeGeneration;

    [TestClass]
    public class TableGenerator_Tests
    {
        public TestContext TestContext { get; set; }

        // https://github.com/benhauman/storelake/issues/7
        [TestMethod]
        public void rowversionsample()
        {
            // the table is part of the test schema (see 'SQL.Tables.')
            TestSchema schema = new TestSchema().LoadTables();
            Assert.IsTrue(schema.tables.TryGetValue("[dbo].[rowversionsample]", out var table), "Table not loaded.");
            Assert.AreEqual(DbType.Binary, ((TestTable)table).columns["chgver"].ColumnDbType, "ROWVERSION column type");

            string code = GenerateTableCode();

            // ROWVERSION is generated by the engine: optional parameter, whatever its nullability (NOT NULL here)
            AssertContains(code, "public rowversionsampleRow AddRowWithValues(int id, string name, string description = null, byte[] chgver = null)");

            // value assigned on insert ...
            AssertContains(code, "this.TableNewRow += new global::System.Data.DataTableNewRowEventHandler(this.RowVersion_TableNewRow);");
            AssertContains(code, "e.Row[\"chgver\"] = this.NextRowVersion();");
            // ... and on every update of the row
            AssertContains(code, "protected override void OnRowChanged(global::System.Data.DataRowChangeEventArgs e)");
            AssertContains(code, "(e.Action == global::System.Data.DataRowAction.Change)");

            // the row's rowversion: offered by the typed row class, not by the table class
            string tableClassCode = GetClassCode(code, "rowversionsampleDataTable");
            string rowClassCode = GetClassCode(code, "rowversionsampleRow");
            AssertContains(rowClassCode, "public long GetRowVersionValueAsLong()");
            AssertNotContains(rowClassCode, "GetRowVersionValue()");
            AssertNotContains(tableClassCode, "GetRowVersionValue");

            // the binary value: read only (get only) like in SQL Server
            string propertyCode = GetPropertyCode(rowClassCode, "public byte[] chgver {");
            AssertContains(propertyCode, "get {");
            AssertNotContains(propertyCode, "set {");
        }

        private static string GetPropertyCode(string classCode, string declaration)
        {
            int start = classCode.IndexOf(declaration, System.StringComparison.Ordinal);
            Assert.IsTrue(start >= 0, "Property not found: " + declaration);
            int end = classCode.IndexOf("\n        }", start, System.StringComparison.Ordinal); // closing brace of the property
            return classCode.Substring(start, end - start);
        }

        private static string GetClassCode(string code, string className)
        {
            string declaration = "public partial class " + className + " ";
            int start = code.IndexOf(declaration, System.StringComparison.Ordinal);
            Assert.IsTrue(start >= 0, "Class not found: " + className);
            int end = code.IndexOf("public partial class ", start + declaration.Length, System.StringComparison.Ordinal);
            return end < 0 ? code.Substring(start) : code.Substring(start, end - start);
        }

        [TestMethod]
        public void hlbiattributeconfig()
        {
            // no ROWVERSION column: no rowversion members
            string code = GenerateTableCode();

            AssertContains(code, "public hlbiattributeconfigRow AddRowWithValues(int id, string objectdefinition, string attributepath, string tablename, string columnname, string description = null)");
            AssertNotContains(code, "RowVersion");
            AssertNotContains(code, "OnRowChanged");
        }

        private string GenerateTableCode()
        {
            string ddl = ResourceHelper.GetSql("SQL.Tables." + TestContext.TestName);
            return TableGenerator.GenerateTablesCode("Test.TestStore", ddl);
        }

        private static void AssertContains(string code, string expected)
        {
            Assert.IsTrue(code.Contains(expected), "Generated code does not contain: " + expected);
        }

        private static void AssertNotContains(string code, string unexpected)
        {
            Assert.IsFalse(code.Contains(unexpected), "Generated code should not contain: " + unexpected);
        }
    }
}
